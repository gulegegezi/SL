def choice(label, intent, effects, lines, results, flag):
    assert len(lines) == 4 and len(results) == 2
    return dict(label=label, intent=intent, effects=effects, lines=lines,
                memory=flag, outcomes=[dict(weight=1, facts=fact, visual=visual,
                  effects=delta, memory=memory) for fact,visual,delta,memory in results])

def event(key, title, ages, stage, scene, actors, prop, facts, npc, lenses, tails, choices,
          *, requires=None, callback=None, cooldown=None):
    assert len(lenses) == len(tails) == 4 and len(choices) == 3
    voices = []
    for index,(narrator,inner,dialogue) in enumerate(lenses):
        voices.append(dict(tier=index,narrator=narrator,inner=inner,dialogue=dialogue,result_tail=tails[index]))
    for ci,c in enumerate(choices):
        c['id'] = f'{key}.C{ci+1}'
        for oi,o in enumerate(c['outcomes']):
            o['id'] = f'{key}.C{ci+1}.O{oi+1}'
            o['voices'] = [dict(tier=i,narrator=o['facts']+' '+tails[i],
                         inner=voices[i]['inner'],dialogue=c['lines'][i]) for i in range(4)]
            o['panels'] = [dict(shot='medium',actors=actors,action=c['intent'],prop=prop,caption=c['label']),
                           dict(shot='wide',actors=actors,action=o['visual'],prop=prop,caption=o['facts']),
                           dict(shot='detail',actors=['lead'],action='settle',prop=prop,voice_ref='selected_outcome.voices[tier]')]
    EVENTS.append(dict(id=key,title=title,age_range=ages,stage=stage,scene=scene,actors=actors,
      prop=prop,facts=facts,npc_dialogue=npc,lenses=voices,choices=choices,
      requirements=requires or {},callback=callback,
      recurrence=dict(once=cooldown is None,cooldown_years=cooldown or 0),
      panels=[dict(shot='wide',actors=actors,action='establish',caption=facts),
              dict(shot='detail',actors=actors,action='look_at_prop',prop=prop,caption=npc),
              dict(shot='medium',actors=['lead'],action='react',voice_ref='lenses[tier]'),
              dict(shot='wide',actors=actors,action='choice_pause',prop=prop)]))

